// Glass live-launch runtime environment.
//
// The Tauri shell cannot start on hosts where namespace creation is restricted.
// GTK resolves its `image-missing` fallback icon through glycin 2.1.1, glycin runs
// its loader under `bwrap --unshare-all`, and `--unshare-all` implies
// `--unshare-net`, which fails with `loopback: Failed RTM_NEWADDR: Operation not
// permitted`. GTK turns that loader failure into
// `Gtk:ERROR ... ensure_surface_for_gicon` and aborts before the window exists.
//
// Verified dead ends (do not reintroduce):
//   * `GLYCIN_SANDBOX_MODE` — glycin 2.1.1 has no such variable. Sandbox selection
//     is the GObject property `GlySandboxSelector`; only `GLYCIN_DATA_DIR` and
//     `GLYCIN_SECCOMP_DEFAULT_ACTION` exist.
//   * `GTK_ICON_THEME_NAME=hicolor` and `GDK_PIXBUF_MODULE_FILE` — no effect.
//   * An empty `GLYCIN_DATA_DIR` conf.d does deregister the loader, but GTK then
//     fails with "No image loaders are configured" instead of falling back.
//
// So the loader must be allowed to run. This materialises a `bwrap` shim that keeps
// every namespace glycin asks for except the network namespace the host denies, and
// puts it ahead of the real `bwrap` on PATH. Sandboxing is preserved; only the
// unavailable netns is dropped.
import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const RUNTIME_DIR = join(REPO_ROOT, "var/glass-runtime");
const SHIM_DIR = join(RUNTIME_DIR, "bin");

function resolveRealBwrap() {
  for (const candidate of ["/usr/bin/bwrap", "/bin/bwrap"]) {
    if (existsSync(candidate)) return candidate;
  }
  try {
    // `command -v` would find our own shim once PATH is prepared, so resolve from
    // the pristine environment instead.
    const found = execFileSync("command", ["-v", "bwrap"], {
      encoding: "utf8",
      shell: "/bin/sh",
    }).trim();
    if (found && !found.startsWith(SHIM_DIR)) return found;
  } catch {
    // fall through
  }
  return null;
}

/**
 * Materialises the shim and returns the environment overlay the Glass needs.
 * Returns `{ env, shim }`; `shim` is null when the host has no bwrap at all, in
 * which case nothing is shimmed and the caller runs unmodified.
 */
export function glassLiveEnv(base = process.env) {
  const realBwrap = resolveRealBwrap();
  const env = { ...base };
  if (!realBwrap) return { env, shim: null };

  mkdirSync(SHIM_DIR, { recursive: true });
  const shim = join(SHIM_DIR, "bwrap");
  writeFileSync(
    shim,
    `#!/bin/sh
# Generated by scripts/glass-live-env.mjs — do not edit.
# Drops only --unshare-net (denied on this host) from --unshare-all.
args=""
for a in "$@"; do
  if [ "$a" = "--unshare-all" ]; then
    args="$args --unshare-user --unshare-ipc --unshare-pid --unshare-uts --unshare-cgroup-try"
  else
    args="$args $a"
  fi
done
exec ${realBwrap} $args
`,
  );
  chmodSync(shim, 0o755);

  env.PATH = `${SHIM_DIR}:${base.PATH ?? ""}`;
  env.LIFEOS_GLASS_BWRAP_SHIM = shim;
  return { env, shim };
}

if (import.meta.main) {
  const { env, shim } = glassLiveEnv();
  console.log(
    JSON.stringify(
      { status: shim ? "ok" : "no-bwrap", shim, path: env.PATH?.split(":")[0] ?? null },
      null,
      2,
    ),
  );
}
